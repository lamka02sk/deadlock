    #[test]
    fn foreign_key_index_note_when_no_index_leads_with_the_columns() {
        let ix = |columns: &[&str]| Index {
            name: "ix".into(),
            parts: columns
                .iter()
                .map(|c| IndexPart {
                    column: (*c).into(),
                    ..IndexPart::default()
                })
                .collect(),
            ..Index::default()
        };
        let mut from = TableStructure {
            indexes: vec![ix(&["b", "a"])],
            ..TableStructure::default()
        };
        let note = |k: &NewForeignKey, s: &TableStructure| foreign_key_index_note(k, s);
        assert_eq!(note(&fk(&["b"], &["x"], "cascade", "cascade"), &from), None);
        assert_eq!(
            note(&fk(&["b", "a"], &["x", "y"], "cascade", "cascade"), &from),
            None
        );
        assert_eq!(
            note(&fk(&["a"], &["x"], "cascade", "cascade"), &from).as_deref(),
            Some("a has no index yet: MySQL adds one with the key's name.")
        );
        assert_eq!(
            note(&fk(&["a", "b"], &["x", "y"], "cascade", "cascade"), &from).as_deref(),
            Some("(a, b) have no index yet: MySQL adds one with the key's name.")
        );
        from.mariadb = true;
        assert!(
            note(&fk(&["a"], &["x"], "cascade", "cascade"), &from)
                .is_some_and(|n| n.contains("MariaDB adds"))
        );
        from.oracle = true;
        assert_eq!(note(&fk(&["a"], &["x"], "cascade", "cascade"), &from), None);
    }

    #[test]
    fn check_sql_and_drop_syntax() {
        let s = TableStructure::default();
        assert_eq!(
            add_check_sql(&t(), "ck", " qty >= 0 ", &s).unwrap(),
            "alter table `my db`.`or``ders` add constraint `ck` check (qty >= 0)"
        );
        assert_eq!(
            add_check_sql(&t(), "", "qty >= 0", &s).unwrap(),
            "alter table `my db`.`or``ders` add check (qty >= 0)"
        );
        assert!(add_check_sql(&t(), "ck", "  ", &s).is_err());
        assert!(add_check_sql(&t(), "ck", "1); drop table x; (1", &s).is_err());
        assert!(add_check_sql(&t(), "ck", "note <> ';'", &s).is_ok());
        let (ot, os) = oracle();
        assert_eq!(
            add_check_sql(&ot, "CK", "qty >= 0", &os).unwrap(),
            r#"alter table "S"."T" add constraint "CK" check (qty >= 0)"#
        );
        assert_eq!(
            s.drop_constraint_sql(&t(), "ck"),
            "alter table `my db`.`or``ders` drop check `ck`"
        );
        let maria = TableStructure {
            mariadb: true,
            ..TableStructure::default()
        };
        assert_eq!(
            maria.drop_constraint_sql(&t(), "ck"),
            "alter table `my db`.`or``ders` drop constraint `ck`"
        );
        assert_eq!(
            os.drop_constraint_sql(&ot, "CK"),
            r#"alter table "S"."T" drop constraint "CK""#
        );
    }

    /// The §3 example: 5 columns, composite primary key, a default, on update (MySQL)
    /// and comments.
    fn orders(oracle: bool) -> NewTable {
        let col = |name: &str, ty: &str, length: &str| NewColumn {
            name: name.into(),
            data_type: ty.into(),
            length: length.into(),
            ..NewColumn::default()
        };
        let (id, int, text, temporal, now) = if oracle {
            ("number", "number", "varchar2", "timestamp", "systimestamp")
        } else {
            (
                "bigint unsigned",
                "int",
                "varchar",
                "datetime",
                "current_timestamp(3)",
            )
        };
        NewTable {
            name: "orders".into(),
            columns: vec![
                NewColumn {
                    auto_increment: true,
                    comment: "row id".into(),
                    ..col("id", id, "")
                },
                col("line", int, if oracle { "10" } else { "" }),
                NewColumn {
                    default: "new".into(),
                    collation: (!oracle).then(|| "utf8mb4_bin".into()),
                    ..col("status", text, "20")
                },
                NewColumn {
                    default: now.into(),
                    on_update: !oracle,
                    ..col("created", temporal, "3")
                },
                NewColumn {
                    nullable: true,
                    comment: "free text".into(),
                    ..col("note", if oracle { "clob" } else { "text" }, "")
                },
            ],
            primary_key: vec!["id".into(), "line".into()],
            engine: (!oracle).then(|| "InnoDB".into()),
            collation: (!oracle).then(|| "utf8mb4_bin".into()),
            comment: "orders".into(),
        }
    }

