/// The types that take `collate`.
const TEXT_TYPES: [&str; 8] = [
    "char",
    "varchar",
    "tinytext",
    "text",
    "mediumtext",
    "longtext",
    "enum",
    "set",
];

/// `varchar` of `varchar`, `int` of `int unsigned`.
fn base_type(data_type: &str) -> String {
    data_type
        .split_whitespace()
        .next()
        .unwrap_or_default()
        .to_ascii_lowercase()
}

/// Whether the type takes a collation (MySQL, MariaDB).
pub fn is_text_type(data_type: &str) -> bool {
    TEXT_TYPES.contains(&base_type(data_type).as_str())
}

/// Whether the type takes `on update current_timestamp` (MySQL, MariaDB).
pub fn is_on_update_type(data_type: &str) -> bool {
    matches!(base_type(data_type).as_str(), "datetime" | "timestamp")
}

/// `(expr)` as it is, anything else in parentheses.
fn parenthesized(expr: &str) -> String {
    let e = expr.trim();
    // Wrapped when the first `(` closes at the end: `(a) + (b)` is not.
    let mut depth = 0usize;
    let mut wrapped = e.starts_with('(');
    for (i, ch) in e.char_indices() {
        match ch {
            '(' => depth += 1,
            ')' => {
                depth = depth.saturating_sub(1);
                if depth == 0 && i + 1 < e.len() {
                    wrapped = false;
                }
            }
            _ => {}
        }
    }
    if wrapped {
        e.to_owned()
    } else {
        format!("({e})")
    }
}

/// The column as it stands inside `add column …`, `change column old …` or
/// `create table (…)`: name and definition, without the position. `key` is
/// `primary key` or `unique key` for an auto-increment column that needs one.
/// Oracle's comment is a statement of its own and is not part of it.
///
/// # Errors
/// An empty name or type, a length that is not a number, a collation that is not a
/// name, or a clause the column cannot take.
pub fn column_definition(
    c: &NewColumn,
    key: Option<&str>,
    s: &TableStructure,
) -> Result<String, String> {
    let name = c.name.trim();
    if name.is_empty() {
        return Err("enter a column name".into());
    }
    if s.oracle {
        return oracle_column_definition(name, c);
    }
    let mut sql = format!(
        "{} {}",
        quote_ident(name),
        full_type(&c.data_type, &c.length, s.backslash_escapes)?
    );
    if let Some(n) = c.srid {
        sql.push_str(&format!(" srid {n}"));
    }
    if let Some(x) = c.collation.as_deref().map(str::trim)
        && !x.is_empty()
        && is_text_type(&c.data_type)
    {
        if !x.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_') {
            return Err(format!("{x} is not a collation"));
        }
        sql.push_str(&format!(" collate {x}"));
    }
    let null = if c.nullable { " null" } else { " not null" };
    let invisible = if c.invisible { " invisible" } else { "" };
    if let Some(g) = &c.generated {
        if c.on_update || c.auto_increment {
            return Err("a generated column takes no on update or auto increment".into());
        }
        if g.expression.trim().is_empty() {
            return Err("enter the expression".into());
        }
        sql.push_str(&format!(
            " generated always as {} {}",
            parenthesized(&g.expression),
            if g.stored { "stored" } else { "virtual" }
        ));
        if !s.mariadb {
            sql.push_str(null);
        }
        sql.push_str(invisible);
    } else if c.auto_increment {
        sql.push_str(" not null");
        sql.push_str(invisible);
        sql.push_str(" auto_increment");
        if let Some(key) = key {
            sql.push_str(&format!(" {key}"));
        }
    } else {
        sql.push_str(null);
        if let Some(d) = default_sql(&c.default, &c.data_type, s.backslash_escapes) {
            sql.push_str(&format!(" default {d}"));
        }
        if c.on_update {
            if !is_on_update_type(&c.data_type) {
                return Err("on update needs a datetime or timestamp column".into());
            }
            // The precision must match the column's, else MySQL error 1294.
            match c.length.trim() {
                "" | "0" => sql.push_str(" on update current_timestamp"),
                n => sql.push_str(&format!(" on update current_timestamp({n})")),
            }
        }
        sql.push_str(invisible);
    }
    if !c.comment.is_empty() {
        sql.push_str(&format!(
            " comment {}",
            quote_str(&c.comment, s.backslash_escapes)
        ));
    }
    if let Some(x) = &c.check {
        sql.push_str(&format!(" check ({x})"));
    }
    Ok(sql)
}

/// ` first`, `` after `x` `` or nothing for the end.
fn position_sql(p: &Position) -> String {
    match p {
        Position::Last => String::new(),
        Position::First => " first".into(),
        Position::After(col) => format!(" after {}", quote_ident(col)),
    }
}

/// The key a new auto-increment column needs: the primary key if there is none.
fn new_key(s: &TableStructure) -> &'static str {
    if s.indexes.iter().any(|i| i.primary) {
        "unique key"
    } else {
        "primary key"
    }
}

/// `alter table … add column …`.
///
/// # Errors
/// An empty name or type, a length that is not a number, or text that would end the
/// statement.
pub fn add_column_sql(
    t: &TableRef,
    c: &NewColumn,
    s: &TableStructure,
) -> Result<Vec<String>, String> {
    if s.oracle {
        return oracle_add_column(t, c, s);
    }
    let key = c.auto_increment.then(|| new_key(s));
    let def = column_definition(c, key, s)?;
    let sql = format!(
        "alter table {} add column {def}{}",
        qualified(t),
        position_sql(&c.position)
    );
    Ok(vec![one_statement(sql, s)?])
}

impl NewColumn {
    /// The form prefilled from an existing column of `s`: the inverse of
    /// [`column_definition`].
    pub fn from_existing(c: &StructureColumn, s: &TableStructure) -> NewColumn {
        let (data_type, length) = split_type(&c.column_type, s.oracle);
        let extra = c.extra.to_ascii_lowercase();
        let i = s.columns.iter().position(|x| x.name == c.name);
        let position = match i {
            Some(0) => Position::First,
            Some(i) => Position::After(s.columns[i - 1].name.clone()),
            None => Position::Last,
        };
        NewColumn {
            name: c.name.clone(),
            data_type,
            length,
            nullable: c.nullable,
            default: c.default.clone().unwrap_or_default(),
            auto_increment: if s.oracle {
                extra.starts_with("generated ")
            } else {
                extra.contains("auto_increment")
            },
            comment: c.comment.clone(),
            position,
            on_update: c.on_update.is_some(),
            // The table's own collation stays implicit, so SHOW CREATE TABLE stays as it is.
            collation: c
                .collation
                .clone()
                .filter(|x| s.facts.collation.as_ref() != Some(x)),
            generated: c.generated.clone(),
            invisible: extra.contains("invisible"),
            srid: c.srid,
            check: c.check.clone(),
        }
    }
}

/// The closing parenthesis of the `(` at `open`, outside `'quoted'` text.
fn closing(text: &str, open: usize) -> Option<usize> {
    let (mut depth, mut quoted) = (0usize, false);
    for (i, ch) in text.char_indices().skip_while(|(i, _)| *i < open) {
        match ch {
            '\'' => quoted = !quoted,
            '(' if !quoted => depth += 1,
            ')' if !quoted => {
                depth = depth.saturating_sub(1);
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

/// `enum` / `set` members from the form's Length: quoted literals as the server writes
/// them in `COLUMN_TYPE` (`'a,b','it''s'`; `''` and `\` escapes in every `sql_mode`),
/// or, when it starts with no quote, bare words split at commas (`a, b`).
fn enum_members(length: &str) -> Result<Vec<String>, String> {
    if !length.starts_with('\'') {
        return Ok(length.split(',').map(|m| m.trim().to_owned()).collect());
    }
    let unclosed = || "a member's quote is not closed".to_owned();
    let mut out = Vec::new();
    let mut chars = length.chars().peekable();
    loop {
        if chars.next() != Some('\'') {
            return Err("quote every member, like 'a','b'".into());
        }
        let mut m = String::new();
        loop {
            match chars.next().ok_or_else(unclosed)? {
                '\'' if chars.peek() == Some(&'\'') => {
                    chars.next();
                    m.push('\'');
                }
                '\'' => break,
                '\\' => match chars.next().ok_or_else(unclosed)? {
                    'n' => m.push('\n'),
                    't' => m.push('\t'),
                    'r' => m.push('\r'),
                    '0' => m.push('\0'),
                    'b' => m.push('\u{8}'),
                    'Z' => m.push('\u{1a}'),
                    // MySQL keeps the backslash of these two.
                    c @ ('%' | '_') => {
                        m.push('\\');
                        m.push(c);
                    }
                    c => m.push(c),
                },
                c => m.push(c),
            }
        }
        out.push(m);
        while chars.next_if(|c| c.is_whitespace()).is_some() {}
        match chars.next() {
            None => return Ok(out),
            Some(',') => while chars.next_if(|c| c.is_whitespace()).is_some() {},
            Some(_) => return Err("separate the members with commas, like 'a','b'".into()),
        }
    }
}

/// A server type as the form's Type and Length: `decimal(10,2) unsigned` →
/// (`decimal unsigned`, `10,2`). Oracle: `number(*,0)` → `integer`,
/// `varchar2(40 char)` → (`varchar2`, `40 char`); anything else it cannot split stays
/// whole as free text.
fn split_type(column_type: &str, oracle: bool) -> (String, String) {
    let ty = column_type.trim();
    if oracle && ty == "number(*,0)" {
        return ("integer".into(), String::new());
    }
    let whole = || (ty.to_owned(), String::new());
    let Some(open) = ty.find('(') else {
        return whole();
    };
    let Some(close) = closing(ty, open) else {
        return whole();
    };
    let (base, inner, rest) = (
        ty[..open].trim(),
        &ty[open + 1..close],
        ty[close + 1..].trim(),
    );
    if oracle && rest.contains('(') {
        // `interval day(2) to second(6)`.
        return whole();
    }
    (
        format!("{base} {rest}").trim().to_owned(),
        inner.trim().to_owned(),
    )
}

/// Edits an existing column. MySQL / MariaDB: one `change column` restating the whole
/// definition and the position. Oracle: only the parts that changed, in up to four
/// statements: rename, modify, identity, comment.
///
/// # Errors
/// What [`column_definition`] refuses, and the changes the engine cannot make in place.
pub fn modify_column_sql(
    t: &TableRef,
    old: &StructureColumn,
    new: &NewColumn,
    s: &TableStructure,
) -> Result<Vec<String>, String> {
    match (&old.generated, &new.generated) {
        (Some(_), None) | (None, Some(_)) => {
            return Err("a generated column stays generated: drop it and add a new one".into());
        }
        (Some(a), Some(b)) if a.stored != b.stored && !s.oracle => {
            return Err(
                "MySQL cannot switch a generated column between stored and virtual: drop it \
                 and add it again"
                    .into(),
            );
        }
        _ => {}
    }
    if s.oracle {
        return oracle_modify_column(t, old, new, s);
    }
    // A column that already leads an index is a key: auto_increment needs no other.
    let keyed = s.indexes.iter().any(|i| {
        i.parts
            .first()
            .is_some_and(|p| !p.expression && p.column == old.name)
    });
    let key = (new.auto_increment && !keyed).then(|| new_key(s));
    // MariaDB writes a column check's own column quoted: a rename renames it there too.
    let renamed;
    let new = match &new.check {
        Some(x) if new.name.trim() != old.name => {
            renamed = NewColumn {
                check: Some(x.replace(&quote_ident(&old.name), &quote_ident(new.name.trim()))),
                ..new.clone()
            };
            &renamed
        }
        _ => new,
    };
    let sql = format!(
        "alter table {} change column {} {}{}",
        qualified(t),
        quote_ident(&old.name),
        column_definition(new, key, s)?,
        position_sql(&new.position)
    );
    Ok(vec![one_statement(sql, s)?])
}

/// What the Edit column form says before Apply about a refusal the server is known to
/// make. Oracle: a type change of a column a virtual column reads fails with ORA-54031.
pub fn modify_column_hints(
    old: &StructureColumn,
    new: &NewColumn,
    s: &TableStructure,
) -> Vec<String> {
    let before = NewColumn::from_existing(old, s);
    let retyped = (before.data_type.trim(), before.length.trim())
        != (new.data_type.trim(), new.length.trim());
    if !s.oracle || !retyped {
        return Vec::new();
    }
    // Oracle writes the columns of a virtual column's expression quoted: `"PRICE"*"QTY"`.
    let ident = oracle_ident(&old.name);
    let readers: Vec<&str> = s
        .columns
        .iter()
        .filter(|c| c.name != old.name)
        .filter(|c| {
            c.generated
                .as_ref()
                .is_some_and(|g| g.expression.contains(&ident))
        })
        .map(|c| c.name.as_str())
        .collect();
    match readers.as_slice() {
        [] => Vec::new(),
        [x] => vec![format!(
            "Oracle cannot change a column that virtual column {x} reads: drop or change {x} first."
        )],
        many => {
            let names = many.join(", ");
            vec![format!(
                "Oracle cannot change a column that virtual columns {names} read: drop or change \
                 them first."
            )]
        }
    }
}

/// What a DDL statement does, in a few words: `rename column`, `modify`, `comment`,
/// `add column`, `create table`. Names "Ran 1 of 3 (rename column)".
pub fn statement_label(sql: &str) -> String {
    let lower = sql.trim().to_ascii_lowercase();
    let words = |text: &str, n: usize| {
        text.split_whitespace()
            .take(n)
            .collect::<Vec<_>>()
            .join(" ")
    };
    if lower.starts_with("comment on column") {
        return "comment".into();
    }
    if lower.starts_with("comment on table") {
        return "table comment".into();
    }
    let Some(rest) = lower.strip_prefix("alter table") else {
        return words(&lower, 2);
    };
    // Past the table's name: identifiers, quoted or not, joined by dots.
    let rest = skip_names(rest);
    let verb = words(rest, 1);
    match verb.as_str() {
        "rename" | "add" | "drop" | "change" => match words(rest, 2).as_str() {
            two @ ("rename column" | "add column" | "change column" | "drop column") => two.into(),
            _ => verb,
        },
        // Oracle: `modify ("C" as (…))`, `modify ("C" drop identity)`, `modify ("C" …)`.
        "modify" => {
            let inner = rest.trim_start()["modify".len()..].trim_start();
            let after = skip_names(inner.strip_prefix('(').unwrap_or(inner));
            match words(after, 2).as_str() {
                w if w.starts_with("as ") => "expression".into(),
                "drop identity)" | "drop identity" => "drop identity".into(),
                _ => verb,
            }
        }
        _ => verb,
    }
}

/// `text` past the leading `a.b`, `` `a`.`b` `` or `"A"."B"` names.
fn skip_names(text: &str) -> &str {
    let mut rest = text.trim_start();
    loop {
        let end = match rest.chars().next() {
            Some(q @ ('`' | '"')) => {
                // A doubled quote stays inside the name.
                let b = rest.as_bytes();
                let mut i = 1;
                while i < b.len() {
                    if b[i] == q as u8 {
                        if b.get(i + 1) == Some(&(q as u8)) {
                            i += 2;
                            continue;
                        }
                        break;
                    }
                    i += 1;
                }
                (i + 1).min(rest.len())
            }
            Some(_) => rest
                .find(|c: char| c.is_whitespace() || c == '.' || c == '(')
                .unwrap_or(rest.len()),
            None => return rest,
        };
        rest = &rest[end..];
        match rest.strip_prefix('.') {
            Some(r) => rest = r,
            None => return rest,
        }
    }
}

/// Oracle's edit: `rename column`, one `modify` with only what changed (restating
/// an unchanged null fails with ORA-01451 / ORA-01442), the expression, the identity,
/// then `comment on column`.
fn oracle_modify_column(
    t: &TableRef,
    old: &StructureColumn,
    new: &NewColumn,
    s: &TableStructure,
) -> Result<Vec<String>, String> {
    if new.on_update {
        return Err("Oracle has no ON UPDATE: use a trigger".into());
    }
    let before = NewColumn::from_existing(old, s);
    if new.position != before.position {
        return Err("Oracle cannot reorder columns".into());
    }
    let name = new.name.trim();
    if name.is_empty() {
        return Err("enter a column name".into());
    }
    if new.auto_increment && !before.auto_increment {
        return Err("Oracle cannot make an existing column an identity column".into());
    }
    let q = oracle_qualified(t);
    let ident = oracle_ident(name);
    let mut out = Vec::new();
    if name != old.name {
        out.push(format!(
            "alter table {q} rename column {} to {ident}",
            oracle_ident(&old.name)
        ));
    }
    let mut parts = String::new();
    if (before.data_type.trim(), before.length.trim()) != (new.data_type.trim(), new.length.trim())
    {
        parts.push_str(&format!(" {}", oracle_type(&new.data_type, &new.length)?));
    }
    if new.generated.is_none() && !new.auto_increment && before.default.trim() != new.default.trim()
    {
        let d = oracle_default(&new.default, &new.data_type).unwrap_or_else(|| "null".into());
        parts.push_str(&format!(" default {d}"));
    }
    if before.nullable != new.nullable {
        parts.push_str(if new.nullable { " null" } else { " not null" });
    }
    if !parts.is_empty() {
        out.push(format!("alter table {q} modify ({ident}{parts})"));
    }
    if let (Some(a), Some(b)) = (&before.generated, &new.generated)
        && a.expression.trim() != b.expression.trim()
    {
        if b.expression.trim().is_empty() {
            return Err("enter the expression".into());
        }
        out.push(format!(
            "alter table {q} modify ({ident} as {})",
            parenthesized(&b.expression)
        ));
    }
    if before.auto_increment && !new.auto_increment {
        out.push(format!("alter table {q} modify ({ident} drop identity)"));
    }
    let mut out = out
        .into_iter()
        .map(|sql| one_statement_in(sql, Engine::Oracle))
        .collect::<Result<Vec<_>, _>>()?;
    if before.comment != new.comment {
        out.push(oracle_comment(t, name, &new.comment)?);
    }
    Ok(out)
}

/// `varchar(255)`, `int(11) unsigned`, `enum('a','b')`.
fn full_type(data_type: &str, length: &str, backslash: bool) -> Result<String, String> {
    let ty = data_type.trim().to_ascii_lowercase();
    if ty.is_empty() {
        return Err("choose a type".into());
    }
    if !ty
        .bytes()
        .all(|b| b.is_ascii_alphanumeric() || b == b' ' || b == b'_')
    {
        return Err(format!("{data_type} is not a type"));
    }
    let length = length.trim();
    if length.is_empty() {
        return match ty.as_str() {
            "varchar" | "varbinary" => Err(format!("{ty} needs a length")),
            "enum" | "set" => Err(format!("{ty} needs its members, like 'a','b'")),
            _ => Ok(ty),
        };
    }
    let inner = if matches!(ty.as_str(), "enum" | "set") {
        let members: Vec<String> = enum_members(length)?
            .iter()
            .map(|m| quote_str(m, backslash))
            .collect();
        members.join(",")
    } else {
        let parts: Vec<&str> = length.split(',').map(str::trim).collect();
        let numbers = parts.len() <= 2
            && parts
                .iter()
                .all(|p| !p.is_empty() && p.bytes().all(|b| b.is_ascii_digit()));
        if !numbers {
            return Err("length must be a number, or two like 10,2".into());
        }
        parts.join(",")
    };
    // The length goes before `unsigned`.
    Ok(match ty.split_once(' ') {
        Some((base, rest)) => format!("{base}({inner}) {rest}"),
        None => format!("{ty}({inner})"),
    })
}

const NUMERIC: [&str; 12] = [
    "tinyint",
    "smallint",
    "mediumint",
    "int",
    "integer",
    "bigint",
    "decimal",
    "numeric",
    "float",
    "double",
    "real",
    "boolean",
];

const TIME_FUNCTIONS: [&str; 5] = [
    "current_timestamp",
    "now",
    "localtime",
    "localtimestamp",
    "current_date",
];

/// `CURRENT_TIMESTAMP`, `now()`, `current_timestamp(3)`: a current-time function with
/// digits at most between the parentheses.
pub(crate) fn is_time_function(text: &str) -> bool {
    let lower = text.trim().to_ascii_lowercase();
    let function = lower.split_once('(').map_or(lower.as_str(), |(f, rest)| {
        let args = rest.strip_suffix(')').unwrap_or("x");
        if args.bytes().all(|b| b.is_ascii_digit()) {
            f
        } else {
            ""
        }
    });
    TIME_FUNCTIONS.contains(&function)
}

/// The typed default as SQL, `None` for no default. `NULL`, the current-time
/// functions, `(expressions)` and `'quoted literals'` stay as typed; numbers for
/// numeric types are written bare; anything else becomes a string literal.
pub fn default_sql(text: &str, data_type: &str, backslash: bool) -> Option<String> {
    let t = text.trim();
    if t.is_empty() {
        return None;
    }
    let lower = t.to_ascii_lowercase();
    let base = base_type(data_type);
    let number = t.parse::<f64>().is_ok_and(f64::is_finite)
        && t.bytes()
            .all(|b| b.is_ascii_digit() || matches!(b, b'.' | b'-' | b'+' | b'e' | b'E'));
    let raw = lower == "null"
        || is_time_function(t)
        || t.starts_with('(') && t.ends_with(')')
        || t.len() >= 2 && t.starts_with('\'') && t.ends_with('\'')
        || number && NUMERIC.contains(&base.as_str())
        || base == "bit" && (lower.starts_with("b'") || t.bytes().all(|b| b.is_ascii_digit()));
    Some(if raw {
        t.to_owned()
    } else {
        quote_str(text, backslash)
    })
}

/// What an index is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IndexKind {
    Index,
    Unique,
    Fulltext,
    Spatial,
    Primary,
    /// Oracle.
    Bitmap,
}

impl IndexKind {
    pub const ALL: [Self; 5] = [
        Self::Index,
        Self::Unique,
        Self::Fulltext,
        Self::Spatial,
        Self::Primary,
    ];

    /// The kinds the Add index form offers on Oracle.
    pub const ORACLE: [Self; 4] = [Self::Index, Self::Unique, Self::Bitmap, Self::Primary];

    pub fn label(self) -> &'static str {
        match self {
            Self::Index => "index",
            Self::Unique => "unique",
            Self::Fulltext => "fulltext",
            Self::Spatial => "spatial",
            Self::Primary => "primary key",
            Self::Bitmap => "bitmap",
        }
    }
}

/// The Add index form. Parts name columns, never expressions.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewIndex {
    /// Empty: the server picks one. Ignored for a primary key.
    pub name: String,
    pub kind: IndexKind,
    pub parts: Vec<IndexPart>,
}

/// `alter table … add index …`.
///
/// # Errors
/// No columns.
pub fn add_index_sql(t: &TableRef, i: &NewIndex, s: &TableStructure) -> Result<String, String> {
    if i.parts.is_empty() {
        return Err("add at least one column".into());
    }
    if s.oracle {
        return oracle_add_index(t, i);
    }
    let parts: Vec<String> = i
        .parts
        .iter()
        .map(|p| {
            let mut s = quote_ident(&p.column);
            if let Some(n) = p.prefix {
                s.push_str(&format!("({n})"));
            }
            if p.descending {
                s.push_str(" desc");
            }
            s
        })
        .collect();
    let name = i.name.trim();
    let named = if name.is_empty() || i.kind == IndexKind::Primary {
        String::new()
    } else {
        format!(" {}", quote_ident(name))
    };
    let kind = match i.kind {
        IndexKind::Index => "index",
        IndexKind::Unique => "unique index",
        IndexKind::Fulltext => "fulltext index",
        IndexKind::Spatial => "spatial index",
        IndexKind::Primary => "primary key",
        IndexKind::Bitmap => return Err("bitmap indexes are Oracle's".into()),
    };
    one_statement(
        format!(
            "alter table {} add {kind}{named} ({})",
            qualified(t),
            parts.join(", ")
        ),
        s,
    )
}

/// The referential actions the Add foreign key form offers on MySQL and MariaDB.
pub const FK_ACTIONS: [&str; 4] = ["restrict", "cascade", "set null", "no action"];
/// Oracle's, for on delete only: it has no on update.
pub const ORACLE_FK_ACTIONS: [&str; 3] = ["no action", "cascade", "set null"];

/// The Add foreign key form.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewForeignKey {
    /// Empty: the server names it.
    pub name: String,
    /// Of this table, in order.
    pub columns: Vec<String>,
    /// In any schema: the statement qualifies it.
    pub ref_table: TableRef,
    /// Paired with `columns` by position.
    pub ref_columns: Vec<String>,
    /// One of [`FK_ACTIONS`], or on Oracle of [`ORACLE_FK_ACTIONS`].
    pub on_delete: String,
    /// MySQL and MariaDB; ignored on Oracle.
    pub on_update: String,
}

/// `alter table … add [constraint n] foreign key (…) references … (…) on delete …
/// on update …`. Oracle writes no clause for `no action`, and no on update.
///
/// # Errors
/// No columns, no referenced table, counts that differ, an action the engine does
/// not offer, or text that ends the statement.
pub fn add_foreign_key_sql(
    t: &TableRef,
    k: &NewForeignKey,
    s: &TableStructure,
) -> Result<String, String> {
    if k.columns.is_empty() {
        return Err("add at least one column".into());
    }
    if k.ref_table.table.is_empty() {
        return Err("pick the table it references".into());
    }
    if k.ref_columns.len() != k.columns.len() {
        return Err(format!(
            "pick a referenced column for each column ({} and {})",
            k.columns.len(),
            k.ref_columns.len()
        ));
    }
    let offered: &[&str] = if s.oracle {
        &ORACLE_FK_ACTIONS
    } else {
        &FK_ACTIONS
    };
    let offer = |what: &str, action: &str| {
        if offered.contains(&action) {
            Ok(())
        } else {
            Err(format!("{what}: pick one of {}", offered.join(", ")))
        }
    };
    offer("on delete", &k.on_delete)?;
    let list = |columns: &[String]| {
        let names: Vec<String> = columns.iter().map(|c| s.ident(c)).collect();
        names.join(", ")
    };
    let name = k.name.trim();
    let named = if name.is_empty() {
        String::new()
    } else {
        format!(" constraint {}", s.ident(name))
    };
    let mut sql = format!(
        "alter table {} add{named} foreign key ({}) references {} ({})",
        s.qualified(t),
        list(&k.columns),
        s.qualified(&k.ref_table),
        list(&k.ref_columns)
    );
    if s.oracle {
        if k.on_delete != "no action" {
            sql.push_str(" on delete ");
            sql.push_str(&k.on_delete);
        }
        return one_statement_in(sql, Engine::Oracle);
    }
    offer("on update", &k.on_update)?;
    sql.push_str(&format!(
        " on delete {} on update {}",
        k.on_delete, k.on_update
    ));
    one_statement(sql, s)
}

/// MySQL / MariaDB: no index of `from` starts with the key's columns in order, so the
/// server adds one named after the key. Plain information, shown under the hints.
pub fn foreign_key_index_note(k: &NewForeignKey, from: &TableStructure) -> Option<String> {
    if from.oracle || k.columns.is_empty() {
        return None;
    }
    let leads = |ix: &Index| {
        ix.parts.len() >= k.columns.len()
            && ix
                .parts
                .iter()
                .zip(&k.columns)
                .all(|(p, c)| !p.expression && p.column.eq_ignore_ascii_case(c))
    };
    if from.indexes.iter().any(leads) {
        return None;
    }
    let server = if from.mariadb { "MariaDB" } else { "MySQL" };
    Some(match k.columns.as_slice() {
        [one] => format!("{one} has no index yet: {server} adds one with the key's name."),
        many => format!(
            "({}) have no index yet: {server} adds one with the key's name.",
            many.join(", ")
        ),
    })
}

/// A column type as foreign keys compare it: the base type and `unsigned`, lower
/// case. `int(11)` is `int`, and `varchar(20)` is `varchar(40)` (MySQL allows it).
fn key_type(column_type: &str) -> (String, bool) {
    let t = column_type.to_ascii_lowercase();
    let base = t
        .split(|c: char| c == '(' || c.is_whitespace())
        .next()
        .unwrap_or_default()
        .to_owned();
    (base, t.contains("unsigned"))
}

/// What the server will likely refuse, as hints shown before Apply (never blocking):
/// column types that differ, referenced columns that are not exactly a primary key or
/// unique key of `to`, text columns whose collations differ, and `set null` on a not
/// null column.
pub fn foreign_key_hints(
    k: &NewForeignKey,
    from: &TableStructure,
    to: &TableStructure,
) -> Vec<String> {
    let mut hints = Vec::new();
    fn column<'a>(s: &'a TableStructure, name: &str) -> Option<&'a StructureColumn> {
        s.columns.iter().find(|c| c.name == name)
    }
    let table = &k.ref_table.table;
    let refuses = match (from.oracle, from.mariadb) {
        (true, _) => "Oracle refuses a key whose column types differ (ORA-02267)",
        (_, true) => "MariaDB refuses a key whose column types differ (error 1005)",
        _ => "MySQL refuses a key whose column types differ (error 3780)",
    };
    for (a, b) in k.columns.iter().zip(&k.ref_columns) {
        let (Some(ca), Some(cb)) = (column(from, a), column(to, b)) else {
            continue;
        };
        if key_type(&ca.column_type) != key_type(&cb.column_type) {
            hints.push(format!(
                "{a} is {} and {table}.{b} is {}. {refuses}: edit column {a} first.",
                ca.column_type, cb.column_type
            ));
        } else if let (Some(x), Some(y)) = (&ca.collation, &cb.collation)
            && !x.eq_ignore_ascii_case(y)
        {
            // Text columns: the character set and the collation must match too.
            let server = if from.mariadb {
                "MariaDB refuses it (error 1005)"
            } else {
                "MySQL refuses it (error 3780)"
            };
            hints.push(format!(
                "{a} uses collation {x} and {table}.{b} uses {y}. {server}: edit column {a} \
                 first."
            ));
        }
    }
    // Oracle needs a primary or unique constraint, not just a unique index (ORA-02270).
    let keys: Vec<Vec<&str>> = to
        .indexes
        .iter()
        .filter(|ix| ix.primary || (ix.unique && (!to.oracle || ix.constraint.is_some())))
        .filter(|ix| ix.parts.iter().all(|p| !p.expression))
        .map(|ix| ix.parts.iter().map(|p| p.column.as_str()).collect())
        .collect();
    let wanted: BTreeSet<&str> = k.ref_columns.iter().map(String::as_str).collect();
    let covers = |key: &[&str]| wanted.iter().all(|c| key.contains(c));
    if !wanted.is_empty()
        && !keys
            .iter()
            .any(|key| key.len() == wanted.len() && covers(key))
    {
        let names = k.ref_columns.join(", ");
        let wider = keys.iter().find(|key| covers(key));
        hints.push(match wider {
            Some(key) => {
                let missing: Vec<&str> = key
                    .iter()
                    .copied()
                    .filter(|c| !wanted.contains(c))
                    .collect();
                format!(
                    "{table} is keyed on ({}): pick {} too, or reference a key of {names} alone.",
                    key.join(", "),
                    missing.join(", ")
                )
            }
            None => {
                let label = match k.ref_columns.as_slice() {
                    [one] => format!("{table}.{one}"),
                    many => format!("{table} ({})", many.join(", ")),
                };
                let primary = to.indexes.iter().find(|ix| ix.primary).map(|ix| {
                    let parts: Vec<&str> = ix.parts.iter().map(|p| p.column.as_str()).collect();
                    parts.join(", ")
                });
                match primary {
                    Some(pk) => format!(
                        "{label} is not a primary key or unique index. Pick {pk}, or add a \
                         unique index on {names} first."
                    ),
                    None => format!(
                        "{label} is not a primary key or unique index: add a unique index on \
                         {names} first."
                    ),
                }
            }
        });
    }
    let set_null = k.on_delete == "set null" || (!from.oracle && k.on_update == "set null");
    if set_null {
        for c in &k.columns {
            if column(from, c).is_some_and(|c| !c.nullable) {
                hints.push(format!(
                    "{c} is not null, and set null needs a nullable column: make {c} nullable first."
                ));
            }
        }
    }
    hints
}

/// `alter table … add [constraint n] check (condition)`. The condition goes as typed:
/// the server's parse error is its only check.
///
/// # Errors
/// An empty condition, or text that ends the statement.
pub fn add_check_sql(
    t: &TableRef,
    name: &str,
    condition: &str,
    s: &TableStructure,
) -> Result<String, String> {
    let condition = condition.trim();
    if condition.is_empty() {
        return Err("enter the expression".into());
    }
    let name = name.trim();
    let named = if name.is_empty() {
        String::new()
    } else {
        format!(" constraint {}", s.ident(name))
    };
    let sql = format!(
        "alter table {} add{named} check ({condition})",
        s.qualified(t)
    );
    one_statement(sql, s)
}

/// `alter table … drop column …`.
pub fn drop_column_sql(t: &TableRef, column: &str, s: &TableStructure) -> String {
    format!(
        "alter table {} drop column {}",
        s.qualified(t),
        s.ident(column)
    )
}

/// `alter table … drop index …`, or `drop primary key`. Oracle: `drop index`, or the
/// constraint the index enforces.
pub fn drop_index_sql(t: &TableRef, index: &Index, s: &TableStructure) -> String {
    match (&index.constraint, index.primary, s.oracle) {
        (_, true, _) => format!("alter table {} drop primary key", s.qualified(t)),
        (Some(c), _, true) => s.drop_constraint_sql(t, c),
        (None, _, true) => format!(
            "drop index {}.{}",
            s.ident(&t.database),
            s.ident(&index.name)
        ),
        (_, _, false) => format!(
            "alter table {} drop index {}",
            s.qualified(t),
            quote_ident(&index.name)
        ),
    }
}

/// `alter table … drop foreign key …`. The index the key used stays.
pub fn drop_foreign_key_sql(t: &TableRef, name: &str, s: &TableStructure) -> String {
    if s.oracle {
        return s.drop_constraint_sql(t, name);
    }
    format!(
        "alter table {} drop foreign key {}",
        s.qualified(t),
        quote_ident(name)
    )
}

/// `rename table a.b to a.c` (MySQL, MariaDB) or `alter table s.t rename to n`
/// (Oracle, where the new name takes no schema: ORA-14047). `to` is trimmed.
///
/// # Errors
/// An empty name, the same name, or text that ends the statement.
pub fn rename_table_sql(t: &TableRef, to: &str, s: &TableStructure) -> Result<String, String> {
    let to = to.trim();
    if to.is_empty() || to == t.table {
        return Err("enter a new name".into());
    }
    if s.oracle {
        let sql = format!("alter table {} rename to {}", s.qualified(t), s.ident(to));
        return one_statement_in(sql, Engine::Oracle);
    }
    let new = TableRef {
        database: t.database.clone(),
        table: to.to_owned(),
    };
    one_statement(
        format!("rename table {} to {}", s.qualified(t), s.qualified(&new)),
        s,
    )
}

/// `truncate table a.b`.
pub fn truncate_table_sql(t: &TableRef, s: &TableStructure) -> String {
    format!("truncate table {}", s.qualified(t))
}

/// `drop table a.b`; on Oracle with `cascade`, `… cascade constraints`, which drops
/// the other tables' keys that point here. `cascade` is ignored elsewhere.
pub fn drop_table_sql(t: &TableRef, cascade: bool, s: &TableStructure) -> String {
    let cascade = if cascade && s.oracle {
        " cascade constraints"
    } else {
        ""
    };
    format!("drop table {}{cascade}", s.qualified(t))
}

/// The New table draft: columns in list order, the primary key by column name.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct NewTable {
    pub name: String,
    /// `position` is ignored: the list order is the column order.
    pub columns: Vec<NewColumn>,
    /// Column names, in key order (which need not be the column order).
    pub primary_key: Vec<String>,
    /// MySQL / MariaDB; `None`: the server default.
    pub engine: Option<String>,
    /// MySQL / MariaDB; `None`: the schema default.
    pub collation: Option<String>,
    pub comment: String,
}

/// The storage engines the New table form offers; MariaDB adds `Aria`.
pub fn table_engines(mariadb: bool) -> Vec<&'static str> {
    let mut v = vec!["InnoDB", "MyISAM", "MEMORY", "ARCHIVE", "CSV"];
    if mariadb {
        v.push("Aria");
    }
    v
}

/// `create table …` and, on Oracle, its `comment on` statements (table first, then
/// the columns in order).
///
/// # Errors
/// No name, no columns, an empty or repeated column name, a primary key column that
/// is not in the list, an auto increment column outside the primary key (MySQL),
/// `on update` on Oracle, an engine or collation that is not a name, or text that
/// ends a statement. Column errors name the column: `column 2 (qty): choose a type`.
pub fn create_table_sql(
    database: &str,
    t: &NewTable,
    s: &TableStructure,
) -> Result<Vec<String>, String> {
    let name = t.name.trim();
    if name.is_empty() {
        return Err("enter a table name".into());
    }
    if t.columns.is_empty() {
        return Err("add a column".into());
    }
    let table = TableRef {
        database: database.to_owned(),
        table: name.to_owned(),
    };
    // Oracle's quoted names are case-sensitive, MySQL's column names are not.
    let same = |a: &str, b: &str| {
        if s.oracle {
            a == b
        } else {
            a.eq_ignore_ascii_case(b)
        }
    };
    let mut lines = Vec::with_capacity(t.columns.len() + 1);
    for (i, c) in t.columns.iter().enumerate() {
        let n = c.name.trim();
        let label = if n.is_empty() {
            format!("column {}", i + 1)
        } else {
            format!("column {} ({n})", i + 1)
        };
        let def = column_definition(c, None, s).map_err(|e| format!("{label}: {e}"))?;
        if t.columns[..i].iter().any(|o| same(o.name.trim(), n)) {
            return Err(format!("{label}: the name is used twice"));
        }
        if c.auto_increment && !s.oracle && !t.primary_key.iter().any(|k| same(k, n)) {
            return Err(format!("{label}: auto increment needs the primary key"));
        }
        lines.push(format!("  {def}"));
    }
    if let Some(k) = t
        .primary_key
        .iter()
        .find(|k| !t.columns.iter().any(|c| same(c.name.trim(), k)))
    {
        return Err(format!("primary key column {k} is not in the list"));
    }
    if !t.primary_key.is_empty() {
        let keys: Vec<String> = t.primary_key.iter().map(|k| s.ident(k)).collect();
        lines.push(format!("  primary key ({})", keys.join(", ")));
    }
    let mut sql = format!(
        "create table {} (\n{}\n)",
        s.qualified(&table),
        lines.join(",\n")
    );
    if s.oracle {
        let mut out = vec![one_statement_in(sql, Engine::Oracle)?];
        if !t.comment.is_empty() {
            out.push(one_statement_in(
                format!(
                    "comment on table {} is {}",
                    oracle_qualified(&table),
                    quote_str(&t.comment, false)
                ),
                Engine::Oracle,
            )?);
        }
        for c in t.columns.iter().filter(|c| !c.comment.is_empty()) {
            out.push(oracle_comment(&table, c.name.trim(), &c.comment)?);
        }
        return Ok(out);
    }
    for (what, noun, value) in [
        ("engine", "an engine", &t.engine),
        ("collate", "a collation", &t.collation),
    ] {
        if let Some(x) = value.as_deref().map(str::trim).filter(|x| !x.is_empty()) {
            if !x.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_') {
                return Err(format!("{x} is not {noun}"));
            }
            sql.push_str(&format!(" {what} = {x}"));
        }
    }
    if !t.comment.is_empty() {
        sql.push_str(&format!(
            " comment = {}",
            quote_str(&t.comment, s.backslash_escapes)
        ));
    }
    Ok(vec![one_statement(sql, s)?])
}

impl TableStructure {
    fn ident(&self, name: &str) -> String {
        if self.oracle {
            oracle_ident(name)
        } else {
            quote_ident(name)
        }
    }

    fn qualified(&self, t: &TableRef) -> String {
        format!("{}.{}", self.ident(&t.database), self.ident(&t.table))
    }

    /// `alter table … drop constraint …`: a check constraint, or on Oracle any
    /// constraint. MySQL writes `drop check`; MariaDB has no `drop check`.
    pub fn drop_constraint_sql(&self, t: &TableRef, name: &str) -> String {
        let verb = if self.oracle || self.mariadb {
            "constraint"
        } else {
            "check"
        };
        format!(
            "alter table {} drop {verb} {}",
            self.qualified(t),
            self.ident(name)
        )
    }
}

fn qualified(t: &TableRef) -> String {
    format!("{}.{}", quote_ident(&t.database), quote_ident(&t.table))
}

// --- Oracle DDL ------------------------------------------------------------------

fn oracle_ident(name: &str) -> String {
    format!("\"{}\"", name.replace('"', "\"\""))
}

fn oracle_qualified(t: &TableRef) -> String {
    format!("{}.{}", oracle_ident(&t.database), oracle_ident(&t.table))
}

/// `alter table … add ("C" type default … not null)`, then `comment on column` when
/// there is a comment. Oracle adds columns at the end only.
fn oracle_add_column(
    t: &TableRef,
    c: &NewColumn,
    s: &TableStructure,
) -> Result<Vec<String>, String> {
    if c.position != Position::Last {
        return Err("Oracle adds columns at the end only".into());
    }
    let def = column_definition(c, None, s)?;
    let mut out = vec![one_statement_in(
        format!("alter table {} add ({def})", oracle_qualified(t)),
        Engine::Oracle,
    )?];
    if !c.comment.is_empty() {
        out.push(oracle_comment(t, c.name.trim(), &c.comment)?);
    }
    Ok(out)
}

/// `comment on column "S"."T"."C" is '…'`; an empty comment clears it.
fn oracle_comment(t: &TableRef, column: &str, comment: &str) -> Result<String, String> {
    one_statement_in(
        format!(
            "comment on column {}.{} is {}",
            oracle_qualified(t),
            oracle_ident(column),
            quote_str(comment, false)
        ),
        Engine::Oracle,
    )
}

/// `"C" type [generated by default as identity | default …] [not null]`, or
/// `"C" [type ]as (expr) virtual`.
fn oracle_column_definition(name: &str, c: &NewColumn) -> Result<String, String> {
    if c.on_update {
        return Err("Oracle has no ON UPDATE: use a trigger".into());
    }
    if let Some(g) = &c.generated {
        if g.expression.trim().is_empty() {
            return Err("enter the expression".into());
        }
        let ty = if c.data_type.trim().is_empty() {
            String::new()
        } else {
            format!(" {}", oracle_type(&c.data_type, &c.length)?)
        };
        return Ok(format!(
            "{}{ty} as {} virtual",
            oracle_ident(name),
            parenthesized(&g.expression)
        ));
    }
    let mut sql = format!(
        "{} {}",
        oracle_ident(name),
        oracle_type(&c.data_type, &c.length)?
    );
    if c.auto_increment {
        sql.push_str(" generated by default as identity");
    } else if let Some(d) = oracle_default(&c.default, &c.data_type) {
        sql.push_str(&format!(" default {d}"));
    }
    if !c.nullable || c.auto_increment {
        sql.push_str(" not null");
    }
    Ok(sql)
}

/// `varchar2(20)`, `number(10,2)`, `timestamp(3) with time zone`.
fn oracle_type(data_type: &str, length: &str) -> Result<String, String> {
    let ty = data_type.trim().to_ascii_lowercase();
    if ty.is_empty() {
        return Err("choose a type".into());
    }
    if !ty
        .bytes()
        .all(|b| b.is_ascii_alphanumeric() || b == b' ' || b == b'_')
    {
        return Err(format!("{data_type} is not a type"));
    }
    let mut length = length.trim();
    if length.is_empty() {
        return match ty.as_str() {
            "varchar2" | "nvarchar2" | "raw" => Err(format!("{ty} needs a length")),
            _ => Ok(ty),
        };
    }
    // `40 char` / `40 byte`: the length semantics of `varchar2` and `char`.
    let mut semantics = "";
    if matches!(ty.as_str(), "varchar2" | "char")
        && let Some((n, unit)) = length.rsplit_once(' ')
    {
        let unit = unit.to_ascii_lowercase();
        if unit == "char" || unit == "byte" {
            semantics = if unit == "char" { " char" } else { " byte" };
            length = n.trim();
        }
    }
    let parts: Vec<&str> = length.split(',').map(str::trim).collect();
    let numbers = parts.len() <= 2
        && parts
            .iter()
            .all(|p| !p.is_empty() && p.bytes().all(|b| b.is_ascii_digit()));
    if !numbers {
        return Err("length must be a number, or two like 10,2".into());
    }
    let inner = parts.join(",");
    match ty.split_once(' ') {
        Some(("timestamp", rest)) if parts.len() == 1 => Ok(format!("timestamp({inner}) {rest}")),
        Some(_) => Err(format!("{ty} takes no length here")),
        None => Ok(format!("{ty}({inner}{semantics})")),
    }
}

const ORACLE_FUNCTIONS: [&str; 7] = [
    "sysdate",
    "systimestamp",
    "current_date",
    "current_timestamp",
    "localtimestamp",
    "user",
    "sys_guid",
];

/// The typed default as Oracle SQL: `NULL`, the clock functions, `(expressions)`,
/// `'quoted literals'` and numbers stay; anything else becomes a string literal.
fn oracle_default(text: &str, data_type: &str) -> Option<String> {
    let t = text.trim();
    if t.is_empty() {
        return None;
    }
    let lower = t.to_ascii_lowercase();
    let function = lower.split_once('(').map_or(lower.as_str(), |(f, rest)| {
        let args = rest.strip_suffix(')').unwrap_or("x");
        if args.bytes().all(|b| b.is_ascii_digit()) {
            f
        } else {
            ""
        }
    });
    let numeric = [
        "number",
        "integer",
        "float",
        "binary_float",
        "binary_double",
    ]
    .contains(&data_type.trim().to_ascii_lowercase().as_str());
    let number = t.parse::<f64>().is_ok_and(f64::is_finite)
        && t.bytes()
            .all(|b| b.is_ascii_digit() || matches!(b, b'.' | b'-' | b'+' | b'e' | b'E'));
    let raw = lower == "null"
        || ORACLE_FUNCTIONS.contains(&function)
        || t.starts_with('(') && t.ends_with(')')
        || t.len() >= 2 && t.starts_with('\'') && t.ends_with('\'')
        || number && numeric;
    Some(if raw {
        t.to_owned()
    } else {
        quote_str(t, false)
    })
}

/// `create [unique|bitmap] index …`, or `alter table … add primary key …`. Oracle
/// needs a name for an index: an empty one becomes `<TABLE>_<COLUMNS>_IX`.
fn oracle_add_index(t: &TableRef, i: &NewIndex) -> Result<String, String> {
    if i.parts.iter().any(|p| p.prefix.is_some()) {
        return Err("Oracle indexes whole columns: leave the prefix empty".into());
    }
    let parts: Vec<String> = i
        .parts
        .iter()
        .map(|p| {
            let mut s = oracle_ident(&p.column);
            if p.descending {
                s.push_str(" desc");
            }
            s
        })
        .collect();
    let name = i.name.trim();
    let sql = match i.kind {
        IndexKind::Primary => {
            let named = if name.is_empty() {
                String::new()
            } else {
                format!(" constraint {}", oracle_ident(name))
            };
            format!(
                "alter table {} add{named} primary key ({})",
                oracle_qualified(t),
                parts.join(", ")
            )
        }
        IndexKind::Index | IndexKind::Unique | IndexKind::Bitmap => {
            let name = if name.is_empty() {
                let mut n = t.table.clone();
                for p in &i.parts {
                    n.push('_');
                    n.push_str(&p.column);
                }
                n.push_str("_IX");
                n.chars().take(128).collect()
            } else {
                name.to_owned()
            };
            let kind = match i.kind {
                IndexKind::Unique => "unique ",
                IndexKind::Bitmap => "bitmap ",
                _ => "",
            };
            format!(
                "create {kind}index {}.{} on {} ({})",
                oracle_ident(&t.database),
                oracle_ident(&name),
                oracle_qualified(t),
                parts.join(", ")
            )
        }
        IndexKind::Fulltext | IndexKind::Spatial => {
            return Err(format!("Oracle has no {} index here", i.kind.label()));
        }
    };
    one_statement_in(sql, Engine::Oracle)
}

/// Refuses text that would run as more than one statement, scanning literals as the
/// session does (`NO_BACKSLASH_ESCAPES`).
fn one_statement(sql: String, s: &TableStructure) -> Result<String, String> {
    let engine = if s.oracle {
        Engine::Oracle
    } else {
        Engine::Mysql
    };
    one_statement_mode(sql, engine, s.backslash_escapes)
}

fn one_statement_in(sql: String, engine: Engine) -> Result<String, String> {
    one_statement_mode(sql, engine, true)
}

fn one_statement_mode(sql: String, engine: Engine, backslash: bool) -> Result<String, String> {
    if crate::split::split_in_mode(&sql, engine, backslash).len() == 1 {
        Ok(sql)
    } else {
        Err("a field ends the statement (;); remove it".into())
    }
}

