    #[test]
    fn create_table_refuses_bad_input() {
        let s = TableStructure::default();
        let good = orders(false);
        let refused = |t: NewTable, s: &TableStructure| create_table_sql("d", &t, s).unwrap_err();
        assert_eq!(
            refused(
                NewTable {
                    name: " ".into(),
                    ..good.clone()
                },
                &s
            ),
            "enter a table name"
        );
        assert_eq!(
            refused(
                NewTable {
                    columns: vec![],
                    ..good.clone()
                },
                &s
            ),
            "add a column"
        );
        let mut t = good.clone();
        t.columns[1].name = "ID".into();
        assert_eq!(refused(t, &s), "column 2 (ID): the name is used twice");
        let mut t = good.clone();
        t.primary_key.push("nope".into());
        assert_eq!(refused(t, &s), "primary key column nope is not in the list");
        let mut t = good.clone();
        t.primary_key = vec!["line".into()];
        assert_eq!(
            refused(t, &s),
            "column 1 (id): auto increment needs the primary key"
        );
        let mut t = good.clone();
        t.engine = Some("InnoDB; drop".into());
        assert_eq!(refused(t, &s), "InnoDB; drop is not an engine");
        let mut t = good.clone();
        t.columns[2].data_type.clear();
        assert_eq!(refused(t, &s), "column 3 (status): choose a type");
        let mut t = good.clone();
        t.columns[2].name.clear();
        assert_eq!(refused(t, &s), "column 3: enter a column name");
        let (_, os) = oracle();
        let mut t = orders(true);
        t.columns[3].on_update = true;
        assert_eq!(
            refused(t, &os),
            "column 4 (created): Oracle has no ON UPDATE: use a trigger"
        );
        // Oracle identity needs no key, and quoted names differ by case.
        let mut t = orders(true);
        t.primary_key.clear();
        t.columns[1].name = "ID".into();
        assert!(create_table_sql("d", &t, &os).is_ok());
    }
