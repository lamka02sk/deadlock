//! A table's structure, engine-neutral: columns, indexes, foreign keys both ways,
//! table facts and the server's own DDL. Below it, the MySQL / MariaDB `alter table`
//! text the Structure view's Add column, Add index, Add foreign key, Add check and
//! drop actions run, and New table's `create table`.

use std::collections::BTreeSet;
use std::fmt;

use crate::connection::Engine;
use crate::edit::{TableRef, quote_ident, quote_str};

/// One column as the Structure view lists it.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct StructureColumn {
    pub name: String,
    /// The full type as the server writes it: `varchar(20)`, `int unsigned`.
    pub column_type: String,
    pub nullable: bool,
    /// The default as SQL: `'pending'`, `0`, `CURRENT_TIMESTAMP`. `None`: no default,
    /// or `NULL`.
    pub default: Option<String>,
    pub generated: Option<Generated>,
    /// What else the server says about it: `auto_increment`, `INVISIBLE`,
    /// `generated by default as identity`.
    pub extra: String,
    pub comment: String,
    pub primary_key: bool,
    pub foreign_key: bool,
    /// MySQL: `COLUMNS.CHARACTER_SET_NAME`; `None` for non-string columns and on Oracle.
    pub charset: Option<String>,
    /// MySQL: `COLUMNS.COLLATION_NAME`. Restated on every CHANGE, else the column falls
    /// back to the table default.
    pub collation: Option<String>,
    /// MySQL: `CURRENT_TIMESTAMP` / `current_timestamp(3)`, as the server writes it;
    /// taken out of `extra`.
    pub on_update: Option<String>,
    /// MySQL 8.0+: `COLUMNS.SRS_ID` of a spatial column. Restated on every CHANGE.
    pub srid: Option<u32>,
    /// MariaDB: the column's own check, as `CHECK_CLAUSE` writes it (a JSON column's
    /// ``json_valid(`doc`)``). `drop constraint` refuses it, and a CHANGE that does not
    /// restate it drops it.
    pub check: Option<String>,
}

/// A generated column's expression, as SQL in parentheses.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Generated {
    pub expression: String,
    /// Stored (`true`) or virtual.
    pub stored: bool,
}

impl StructureColumn {
    /// The Default cell: the default, or the generation expression, then `on update`
    /// and the extra.
    pub fn default_label(&self) -> String {
        let first = match (&self.generated, &self.default) {
            (Some(g), _) => format!(
                "generated always as {} {}",
                g.expression,
                if g.stored { "stored" } else { "virtual" }
            ),
            (None, Some(d)) => d.clone(),
            (None, None) => String::new(),
        };
        let on_update = self
            .on_update
            .as_ref()
            .map(|u| format!("on update {u}"))
            .unwrap_or_default();
        [first.as_str(), on_update.as_str(), self.extra.as_str()]
            .into_iter()
            .filter(|s| !s.is_empty())
            .collect::<Vec<_>>()
            .join(" ")
    }

    /// `PK`, `FK`, `PK FK` or nothing.
    pub fn key_label(&self) -> &'static str {
        match (self.primary_key, self.foreign_key) {
            (true, true) => "PK FK",
            (true, false) => "PK",
            (false, true) => "FK",
            (false, false) => "",
        }
    }
}

/// One key part of an index.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct IndexPart {
    /// A column name, or a functional key part's expression.
    pub column: String,
    pub expression: bool,
    pub descending: bool,
    /// Only the first `n` characters or bytes are indexed.
    pub prefix: Option<u32>,
}

impl fmt::Display for IndexPart {
    /// `title(50)`, `created desc`, `(lower(email))`.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.expression {
            write!(f, "({})", self.column)?;
        } else {
            f.write_str(&self.column)?;
        }
        if let Some(n) = self.prefix {
            write!(f, "({n})")?;
        }
        if self.descending {
            f.write_str(" desc")?;
        }
        Ok(())
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Index {
    pub name: String,
    pub parts: Vec<IndexPart>,
    /// The engine's method: `BTREE`, `HASH`, `FULLTEXT`, `SPATIAL`.
    pub kind: String,
    pub unique: bool,
    pub primary: bool,
    /// Oracle: the primary or unique constraint this index enforces, which a drop
    /// removes instead of the index.
    pub constraint: Option<String>,
}

impl Index {
    /// The Kind cell: `primary`, `unique`, `fulltext`, `btree`.
    pub fn kind_label(&self) -> String {
        let method = self.kind.to_ascii_lowercase();
        if self.primary {
            "primary".into()
        } else if self.unique && method == "btree" {
            "unique".into()
        } else if self.unique {
            format!("unique {method}")
        } else {
            method
        }
    }

    /// The Columns cell: `qty desc, created`.
    pub fn parts_label(&self) -> String {
        let parts: Vec<String> = self.parts.iter().map(ToString::to_string).collect();
        parts.join(", ")
    }
}

/// A foreign key, from the referencing table to the referenced one.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ForeignKey {
    pub name: String,
    pub from: TableRef,
    pub from_columns: Vec<String>,
    pub to: TableRef,
    pub to_columns: Vec<String>,
    /// Lower case: `cascade`, `set null`, `restrict`, `no action`.
    pub on_delete: String,
    /// As `on_delete`; empty on Oracle, which has no ON UPDATE.
    pub on_update: String,
}

/// What the server knows about the table as a whole.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct TableFacts {
    pub engine: Option<String>,
    pub collation: Option<String>,
    /// From the server's statistics: an estimate for InnoDB. A 0 is checked against
    /// the table, so `Some(0)` means no rows; `None`: not known.
    pub rows: Option<u64>,
    pub data_bytes: Option<u64>,
    pub index_bytes: Option<u64>,
    pub comment: String,
    /// Oracle: where the rows are stored.
    pub tablespace: Option<String>,
}

impl TableFacts {
    /// Data plus indexes, when the server reports either.
    pub fn size(&self) -> Option<u64> {
        match (self.data_bytes, self.index_bytes) {
            (None, None) => None,
            (d, i) => Some(d.unwrap_or(0).saturating_add(i.unwrap_or(0))),
        }
    }
}

/// A table's or view's structure. Views have columns and the DDL only.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct TableStructure {
    pub view: bool,
    pub columns: Vec<StructureColumn>,
    pub indexes: Vec<Index>,
    /// Keys of this table.
    pub foreign_keys: Vec<ForeignKey>,
    /// Keys of other tables (or this one) that point at this table.
    pub referenced_by: Vec<ForeignKey>,
    pub facts: TableFacts,
    /// Check constraints (all three engines).
    pub checks: Vec<Check>,
    /// MySQL before 8.0.16, MariaDB before 10.2.22: no `CHECK_CONSTRAINTS` view, so
    /// checks are neither listed nor offered.
    pub checks_unsupported: bool,
    /// `CREATE TABLE …` or `CREATE VIEW …`, as the server writes it.
    pub ddl: String,
    /// The session treats `\` in strings as an escape (no `NO_BACKSLASH_ESCAPES`).
    pub backslash_escapes: bool,
    /// Oracle: `"names"` and Oracle DDL.
    pub oracle: bool,
    /// MariaDB: no `null` / `not null` on generated columns, `drop constraint` for checks.
    pub mariadb: bool,
}

/// A check constraint.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Check {
    pub name: String,
    /// The condition as the server writes it: `total >= 0`.
    pub condition: String,
    /// Off (`DISABLE`): the server does not enforce it.
    pub enabled: bool,
}

/// `214 MB`, `16 KB`, `512 B`.
pub fn size_label(bytes: u64) -> String {
    const UNITS: [&str; 5] = ["B", "KB", "MB", "GB", "TB"];
    let mut value = bytes;
    let mut unit = 0;
    // Whole units, rounded down: the summary line needs no decimals.
    while value >= 1024 && unit + 1 < UNITS.len() {
        value /= 1024;
        unit += 1;
    }
    format!("{value} {}", UNITS[unit])
}

